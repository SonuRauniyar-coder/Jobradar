-- Long text columns use unbounded VARCHAR: it behaves the same on PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE user_settings (
    user_id             BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    profile_keywords    VARCHAR(4000) NOT NULL DEFAULT '',
    preferred_locations VARCHAR(4000) NOT NULL DEFAULT '',
    scan_concurrency    INT           NOT NULL DEFAULT 10,
    rate_limit_per_sec  DOUBLE PRECISION NOT NULL DEFAULT 1.0
);

CREATE TABLE company_lists (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_company_lists_user_name UNIQUE (user_id, name)
);

CREATE TABLE companies (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id             BIGINT       NOT NULL REFERENCES company_lists (id) ON DELETE CASCADE,
    name                VARCHAR(255) NOT NULL,
    website             VARCHAR(1000),
    career_url          VARCHAR(1000),
    location_preference VARCHAR(255),
    source_type         VARCHAR(32)  NOT NULL DEFAULT 'UNKNOWN',
    source_locked       BOOLEAN      NOT NULL DEFAULT FALSE,
    ats_slug            VARCHAR(255),
    last_scanned_at     TIMESTAMP WITH TIME ZONE,
    last_status         VARCHAR(32),
    last_error          VARCHAR(2000),
    jobs_count          INT          NOT NULL DEFAULT 0
);
CREATE INDEX idx_companies_list ON companies (list_id);

CREATE TABLE jobs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            BIGINT        NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    external_id           VARCHAR(255),
    title                 VARCHAR(500)  NOT NULL,
    department            VARCHAR(255),
    location              VARCHAR(500),
    work_mode             VARCHAR(16)   NOT NULL DEFAULT 'UNKNOWN',
    employment_type       VARCHAR(64),
    experience_raw        VARCHAR(255),
    min_years             INT,
    max_years             INT,
    category              VARCHAR(16)   NOT NULL DEFAULT 'UNSPECIFIED',
    category_overridden   BOOLEAN       NOT NULL DEFAULT FALSE,
    classification_reason VARCHAR(1000),
    role_category         VARCHAR(32)   NOT NULL DEFAULT 'OTHER',
    skills                VARCHAR(2000),
    description           VARCHAR,
    apply_url             VARCHAR(2000),
    source_url            VARCHAR(2000),
    posted_at             TIMESTAMP WITH TIME ZONE,
    first_seen_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    status_open           BOOLEAN       NOT NULL DEFAULT TRUE,
    content_hash          VARCHAR(64)   NOT NULL
);
CREATE INDEX idx_jobs_company ON jobs (company_id);
CREATE INDEX idx_jobs_category ON jobs (category);
CREATE INDEX idx_jobs_first_seen ON jobs (first_seen_at);
CREATE INDEX idx_jobs_content_hash ON jobs (content_hash);

CREATE TABLE job_user_status (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    job_id         BIGINT      NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    status         VARCHAR(16) NOT NULL,
    applied_at     TIMESTAMP WITH TIME ZONE,
    notes          VARCHAR(4000),
    follow_up_date DATE,
    CONSTRAINT uq_job_user_status UNIQUE (user_id, job_id)
);
CREATE INDEX idx_job_user_status_job ON job_user_status (job_id);

CREATE TABLE scan_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE,
    total           INT         NOT NULL DEFAULT 0,
    success         INT         NOT NULL DEFAULT 0,
    failed          INT         NOT NULL DEFAULT 0,
    current_company VARCHAR(255),
    state           VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
    triggered_by    VARCHAR(32) NOT NULL
);

CREATE TABLE scan_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_run_id BIGINT      NOT NULL REFERENCES scan_runs (id) ON DELETE CASCADE,
    company_id  BIGINT      NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    status      VARCHAR(16) NOT NULL,
    jobs_found  INT         NOT NULL DEFAULT 0,
    error       VARCHAR(2000),
    duration_ms BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX idx_scan_logs_run ON scan_logs (scan_run_id);

CREATE TABLE saved_searches (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name         VARCHAR(255) NOT NULL,
    filters_json VARCHAR(4000) NOT NULL,
    email_alert  BOOLEAN      NOT NULL DEFAULT FALSE
);
